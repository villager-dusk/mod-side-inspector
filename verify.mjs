import assert from 'node:assert/strict';
import {zipSync,strToU8} from 'fflate';
import {analyzeFile} from './analyzer.js';
import {mkdirSync,writeFileSync} from 'node:fs';
const make=(entries,name='fixture.jar',options={})=>new File([zipSync(Object.fromEntries(Object.entries(entries).map(([k,v])=>[k,strToU8(typeof v==='string'?v:JSON.stringify(v))])),options)],name);
const fabric=(env)=>({'fabric.mod.json':{schemaVersion:1,id:'test_mod',name:'中文测试',version:'1.0',...(env===undefined?{}:{environment:env})}});
let passed=0;
async function check(label,entries,category,options){const r=await analyzeFile(make(entries,'fixture.jar',options));assert.equal(r.category,category,label+': '+JSON.stringify(r));passed++;return r;}
await check('Fabric client',fabric('client'),'client');
await check('Fabric server',fabric('server'),'server');
await check('Fabric wildcard',fabric('*'),'both');
await check('Fabric default',fabric(),'both');
await check('Fabric unknown env',fabric('CLIENT'),'error');
await check('Uncompressed JAR',fabric('client'),'client',{level:0});
await check('Malformed JSON',{'fabric.mod.json':'{broken'},'error');
await check('Malformed identity',{'fabric.mod.json':{name:'missing ID'}},'error');
for(const [env,category]of [['client','client'],['dedicated_server','server'],['*','both'],[undefined,'both']])await check('Quilt '+env,{'quilt.mod.json':{schema_version:1,quilt_loader:{id:'quilt_test',version:'1'},minecraft:env===undefined?{}:{environment:env}}},category);
const forge='modLoader="javafml"\nloaderVersion="[47,)"\nlicense="MIT"\n';
const mods='\n[[mods]]\nmodId="forge_test"\ndisplayName="中文 Forge"\nversion="1"\n';
await check('Forge client flag',{'META-INF/mods.toml':forge+'clientSideOnly=true\n'+mods},'client');
await check('Forge nested flag not mod-wide',{'META-INF/mods.toml':forge+mods+'clientSideOnly=true'},'unknown');
await check('Forge false not both',{'META-INF/mods.toml':forge+'clientSideOnly=false\n'+mods},'unknown');
await check('Forge displayTest not side',{'META-INF/mods.toml':forge+mods+'displayTest="IGNORE_ALL_VERSION"\n[[dependencies.forge_test]]\nmodId="minecraft"\nside="CLIENT"'},'unknown');
await check('NeoForge flag ignored',{'META-INF/neoforge.mods.toml':forge+'clientSideOnly=true\n'+mods},'unknown');
await check('Broken TOML',{'META-INF/mods.toml':'invalid = [bad'},'error');
await check('Library',{'example.class':'stub'},'unknown');
await check('Legacy info',{'mcmod.info':[{modid:'old',name:'Old Mod',version:'1'}]},'unknown');
await check('Conflicting loaders',{...fabric('client'),'quilt.mod.json':{schema_version:1,quilt_loader:{id:'quilt_test'},minecraft:{environment:'dedicated_server'}}},'unknown');
await check('Modern metadata wins legacy',{...fabric('client'),'mcmod.info':[{modid:'old'}]},'client');
await check('Oversized metadata',{'fabric.mod.json':' '.repeat(2*1024*1024+1)},'error');
const broken=await analyzeFile(new File(['not a zip'],'broken.jar'));assert.equal(broken.category,'error');passed++;
const crcBytes=new Uint8Array(await make(fabric('client'),'crc.jar',{level:0}).arrayBuffer());crcBytes[46]^=1;
assert.equal((await analyzeFile(new File([crcBytes],'crc.jar'))).category,'error');passed++;
mkdirSync('test-results/fixtures/mods/sub',{recursive:true});
writeFileSync('test-results/fixtures/mods/client.jar',Buffer.from(await make(fabric('client')).arrayBuffer()));
writeFileSync('test-results/fixtures/mods/sub/server.jar',Buffer.from(await make(fabric('server')).arrayBuffer()));
writeFileSync('test-results/fixtures/mods/readme.txt','ignored');
writeFileSync('test-results/fixtures/mods/broken.jar','not zip');
writeFileSync('test-results/fixtures/mods/forge.jar',Buffer.from(await make({'META-INF/mods.toml':forge+mods}).arrayBuffer()));
writeFileSync('test-results/fixtures/mods/xss.jar',Buffer.from(await make({'fabric.mod.json':{schemaVersion:1,id:'xss_test',name:'<img src=x onerror=alert(1)>',environment:'client'}}).arrayBuffer()));
console.log(JSON.stringify({passed,checks:'运行端声明、默认值、冲突、旧版兼容、损坏、CRC、体积上限、TOML 依赖端误判'}));
